import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { PUBLIC_PLAYERS, createDemoSocial, migrateSocial, stableDmId } from '../js/features/chat.js';
import { creatorStarsForRatio, validateCreatorDraft } from '../js/features/creator.js';
import { blindAttemptLimit, borrowAttemptLimit } from '../js/features/team.js';
import { SCREENS } from '../js/core/navigation.js';
const local = 'local-user-you';
assert.equal(new Set(PUBLIC_PLAYERS.map(p => p.id)).size, PUBLIC_PLAYERS.length);
assert.ok(PUBLIC_PLAYERS.length >= 5);
for (const player of PUBLIC_PLAYERS) assert.ok(existsSync(player.avatar), player.avatar);
const fresh = createDemoSocial(local);
assert.equal(fresh.social.friends.length, 2);
assert.equal(PUBLIC_PLAYERS.filter(p => !fresh.social.friends.includes(p.id)).length, 3);
for (const friendId of fresh.social.friends) {
  const room = fresh.rooms[stableDmId(local, friendId)];
  assert.equal(room.messages.length, 3);
  assert.ok(room.messages.every(m => m.authorId === local || m.authorId === friendId));
}
const removed = structuredClone(fresh.social); removed.friends = [];
assert.deepEqual(migrateSocial(removed).friends, []);
assert.deepEqual(migrateSocial(null).friends, []);
assert.equal(stableDmId(local, 'sim-user-maya'), stableDmId('sim-user-maya', local));
assert.deepEqual([100,80,79.9,60,59.9,40,39.9,20,19.9,0].map(creatorStarsForRatio),[1,1,2,2,3,3,4,4,5,0]);
// Version 3 stores clues in five difficulty slots; three-star drafts use slots 2–4.
const valid={version:3,fragmentData:'test',fullData:'test',crop:{x:0,y:0,w:.5,h:1},stars:3,details:{title:'QA study',artist:'QA creator',comment:'Warm colour meets a quiet edge.',clues:['','','A warm tone.','A straight edge.','Half of a square.']}};
assert.equal(validateCreatorDraft(valid),'');
assert.match(validateCreatorDraft({...valid,details:{...valid.details,clues:['One clue.']}}),/exactly 3/);
const html=readFileSync('index.html','utf8');
assert.deepEqual([1,2,3,4,5].map((stars) => borrowAttemptLimit(stars, 1)),[1,2,3,4,5]);
assert.deepEqual([1,2,3,4,5].map((size) => borrowAttemptLimit(5, size)),[5,4,3,2,1]);
assert.deepEqual([1,2,3,4,5].map(blindAttemptLimit),[2,3,4,5,6]);
assert.equal(borrowAttemptLimit(1, 3),-1);
const routes = [...html.matchAll(/data-screen="([^"]+)"/g)].map(match => match[1]);
assert.equal(new Set(routes).size, routes.length, 'Screen routes must be unique');
assert.deepEqual([...routes].sort(), Object.values(SCREENS).sort(), 'Markup must match registered routes');
assert.match(html,/data-screen="login"/);
assert.match(html,/data-action="demo-login"/);
assert.ok(!html.includes('${'));
for(const match of readFileSync('css/style.css','utf8').matchAll(/@import\s+url\(["']?([^"')]+)/g))assert.ok(existsSync('css/'+match[1]));
console.log(`PASS: stable social data, creator validation, Borrow/Blind attempt formulas including zero/negative edge, login entry, ${routes.length} registered routes, CSS imports.`);
